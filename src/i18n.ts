/** Idioma de la interfaz: el de Obsidian si es español; inglés en cualquier otro caso. */
export const uiLanguage: 'en' | 'es' = getLanguage().toLowerCase().startsWith('es') ? 'es' : 'en';

const dictionary: Record<Key, string> = uiLanguage === 'es' ? es : en;

export function t(key: Key, vars: Record<string, string | number> = {}): string {
	return dictionary[key].replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}
